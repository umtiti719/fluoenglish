/* Kart arkası ve Defterim için küçük kelime ailesi kutusu */
function famHtml(en){
  const f=FAMILY[en];if(!f)return "";
  const fam=f[0]?f[0].split("|").map(x=>x.split("·")):[],syn=f[1]?f[1].split(/,\s*/):[],ant=f[2]?f[2].split(/,\s*/):[];
  let h='';
  if(fam.length)h+='<div class="fam-r"><span class="fam-l">Aile</span><div class="fam-v">'+fam.map(([w,p,t])=>'<span class="fam-w"><b data-say="'+esc(w)+'">'+esc(w)+'</b><i>'+esc(p)+'</i>'+esc(t)+'</span>').join("")+'</div></div>';
  if(syn.length)h+='<div class="fam-r"><span class="fam-l s">≈ Eş</span><div class="fam-v">'+syn.map(s=>'<span class="fam-c">'+esc(s)+'</span>').join("")+'</div></div>';
  if(ant.length)h+='<div class="fam-r"><span class="fam-l a">≠ Zıt</span><div class="fam-v">'+ant.map(s=>'<span class="fam-c">'+esc(s)+'</span>').join("")+'</div></div>';
  return h;
}
